def wilson(k, n):
    z = 1.96
    center = (k/n + z*z/(2*n)) / (1 + z*z/n)
    radius = z*((k/n*(1-k/n)/n + z*z/(4*n*n))**.5)/(1+z*z/n)
    return f"{100*(center-radius):.1f}–{100*(center+radius):.1f}%"


